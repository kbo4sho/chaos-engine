// Each recommended level requires the named spare to act in every certified repair.
import fs from 'node:fs';
import M from 'matter-js';
import { campaign } from '../one-part-missing/campaign.js';
import { practice } from '../one-part-missing/learning.js';
import { certify } from '../one-part-missing/certify.js';
import { parts, createRun, advance } from '../one-part-missing/machines.js';
import { toolEvents } from '../one-part-missing/tool-evidence.js';
const result = Object.fromEntries(Object.keys(parts).map((kind) => [kind, { fit: [], combine: [] }]));
for (const [i, machine] of campaign.entries()) {
  const moves = certify(M, machine);
  if (!moves?.length) throw Error('Uncertified ' + machine.id);
  const observed = moves.map((move) => {
    const run = createRun(M, machine, move);
    while (run.state === 'running') advance(M, run);
    return toolEvents(machine, move, run);
  });
  const grade = (machine.capacity || 1) > 1 ? 'combined' : 'fitted',
    key = grade === 'fitted' ? 'fit' : 'combine';
  for (const kind of machine.tray)
    if (observed.every((rows) => rows.some((row) => row.grade === grade && row.kind === kind)))
      result[kind][key].push(i + 1);
}
const concise = {};
for (const [kind, { fit, combine }] of Object.entries(result)) {
  const select = (set, prefer) =>
    [...new Set([...prefer.filter((n) => set.includes(n)), ...set])].slice(0, 3);
  concise[kind] = [select(fit, practice[kind]), select(combine, [practice[kind][2]])];
}
const lines = Object.entries(concise).map(([k, v]) => '  ' + k + ': ' + JSON.stringify(v) + ',');
fs.writeFileSync(
  new URL('../one-part-missing/practice-targets.js', import.meta.url),
  '// Generated by scripts/author-tool-practice.mjs from every certified solution.\nexport const practiceTargets = {\n' +
    lines.join('\n') +
    '\n};\n',
);
console.log(
  'Tools with a solo or compound fitting',
  Object.values(concise).filter((v) => v.some((a) => a.length)).length,
);
console.log(
  'No solo or compound machine',
  Object.entries(concise).filter(([, v]) => v.some((a) => !a.length)),
);
