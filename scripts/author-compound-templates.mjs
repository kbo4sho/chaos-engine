// Retain stock only when every included spare acts and no shorter tray setup
// can deliver at any of the seven release offsets used by the design bench.
import fs from 'node:fs';
import M from 'matter-js';
import { pairFinals } from '../one-part-missing/pair-training-index.js';
import { campaign } from '../one-part-missing/campaign.js';
import { certify, possibilities } from '../one-part-missing/certify.js';
import { fittings, trial } from '../one-part-missing/machines.js';
import { recordSimulation } from '../one-part-missing/attempt-film.js';
import { toolEvents } from '../one-part-missing/tool-evidence.js';
const offsets = [-3, -2, -1, 0, 1, 2, 3],
  rows = [];
for (const n of [...new Set(Object.values(pairFinals).flat())].sort((a, b) => a - b)) {
  const m = campaign[n - 1],
    winning = certify(M, m);
  const move = winning.find(
    (f) =>
      offsets.every((j) => trial(M, m, f, j).state === 'won') &&
      toolEvents(m, f, recordSimulation(M, m, f).run).filter((e) => e.grade === 'fitted').length ===
        m.capacity,
  );
  if (!move) continue;
  let shortcut = false;
  for (let i = 1; i < m.capacity && !shortcut; i++)
    for (const p of possibilities(m, i))
      if (offsets.some((j) => trial(M, m, p, j).state === 'won')) {
        shortcut = true;
        break;
      }
  if (!shortcut)
    rows.push([n, fittings(m, move).map((f) => [f.part, f.socket, ...(f.flipped ? [1] : [])])]);
}
fs.writeFileSync(
  new URL('../one-part-missing/compound-templates.js', import.meta.url),
  '// Generated by scripts/author-compound-templates.mjs. Published level numbers and base fittings are stable.\nexport const compoundTemplates = [\n' +
    rows.map((r) => '  ' + JSON.stringify(r) + ',\n').join('') +
    '];\n',
);
console.log(rows.length + ' compound design templates.');
