// Index working tools from actual successful runs, including both work-order benchmarks.
import fs from 'node:fs';
import M from 'matter-js';
import { campaign } from '../one-part-missing/campaign.js';
import { parts, createRun, advance } from '../one-part-missing/machines.js';
import { certify } from '../one-part-missing/certify.js';
import { orders } from '../one-part-missing/work-orders.js';
import { benchmarks } from './lib/work-order-benchmarks.mjs';
const tools = Object.keys(parts).sort(),
  rows = [];
for (const [i, m] of [...campaign, ...orders].entries()) {
  const moves = i < campaign.length ? certify(M, m) : benchmarks[i - campaign.length];
  const active = new Set();
  for (const move of moves) {
    const r = createRun(M, m, move);
    while (r.state === 'running') advance(M, r);
    if (r.state !== 'won') throw Error('Unfinished index run for ' + m.id);
    for (const event of r.uses) active.add(event.kind);
  }
  rows.push(
    [...active]
      .map((k) => tools.indexOf(k).toString(36))
      .sort()
      .join('.'),
  );
}
const out = new URL('../one-part-missing/library-index.js', import.meta.url);
fs.writeFileSync(
  out,
  '// Working parts observed during solved runs. Generated by scripts/author-library-index.mjs.\nexport const indexedTools = ' +
    JSON.stringify(tools) +
    ';\nexport const workingParts = [\n' +
    Array.from(
      { length: Math.ceil(rows.length / 10) },
      (_, i) =>
        '  ' +
        rows
          .slice(i * 10, i * 10 + 10)
          .map((s) => JSON.stringify(s))
          .join(',') +
        ',\n',
    ).join('') +
    '];\n',
);
