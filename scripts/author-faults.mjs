import fs from 'node:fs';
import M from 'matter-js';
import { campaign } from '../one-part-missing/campaign.js';
import { parts, trial } from '../one-part-missing/machines.js';
import { certify } from '../one-part-missing/certify.js';
import {
  inspectionLine,
  fieldMachine,
  tapeFor,
  firstDifference,
} from '../one-part-missing/fault-desk/physics.js';
const cases = [
  [126, 'Return belt', 'conveyor', ['reverse', 'offline']],
  [118, 'Short rebound', 'trampoline', ['shift', 'offline']],
  [222, 'Spring gauge', 'spring', ['slack', 'offline']],
  [372, 'Canopy test', 'parachute', ['offline', 'shift']],
  [456, 'Shutter clearance', 'phase', ['shift', 'offline']],
  [289, 'Power coupling', 'clutch', ['offline']],
  [141, 'The air mail bench', 'magnet', ['shift', 'offline']],
  [179, 'Interrupted stroke', 'piston', ['shift', 'offline']],
  [343, 'Crossing wire', 'zipline', ['shift', 'offline']],
  [317, 'The output shaft', 'motor', ['reverse', 'rate', 'offline']],
  [395, 'Parcel skid', 'keel', ['shift', 'offline']],
  [433, 'The cable works', 'pulley', ['slack', 'offline']],
  [425, 'Sorting office', 'sieve', ['offline', 'wide', 'shift']],
  [474, 'The screened turn', 'swirl', ['reverse', 'shift', 'offline']],
  [483, 'Two control points', 'switch', ['shift', 'offline']],
  [494, 'Late discharge', 'ground', ['shift', 'offline']],
  [498, 'Across two departments', 'deflector', ['reverse', 'shift', 'offline']],
  [500, 'Last call at dispatch', 'swirl', ['reverse', 'shift', 'offline']],
];
function adjustments(s, mode) {
  if (mode === 'offline') return [{ disabled: true }];
  if (mode === 'reverse') return [{ dir: -(s.dir || 1) }];
  if (mode === 'rate') return [{ rate: (s.rate || 0.04) * 0.35 }];
  if (mode === 'slack')
    return [{ rest: (s.rest || 1) * 1.6 }, { rest: (s.rest || 1) * 0.55 }];
  if (mode === 'wide') return [{ gap: (s.gap || 28) * 1.7 }];
  return [
    [32, 0],
    [-32, 0],
    [0, 34],
    [0, -34],
    [48, 0],
    [-48, 0],
  ]
    .map(([dx, dy]) => ({ x: s.x + dx, y: s.y + dy }))
    .filter((v) => v.x > 28 && v.x < 692 && v.y > 22 && v.y < 358);
}
const casesOut = [];
for (const [n, title, kind, options] of cases) {
  const m = campaign[n - 1],
    fit = certify(M, m)[0],
    line = inspectionLine(m, fit),
    station = line.findIndex((s) => s.kind === kind),
    shape = line[station];
  const full = fieldMachine(m, fit, station, {}, station),
    reference = tapeFor(M, full);
  const indices = line.flatMap((s, k) =>
    parts[s.kind] &&
    trial(M, {
      ...full,
      fixtures: line.map((p, i) => (k === i ? { ...p, disabled: true } : p)),
    }).state === 'miss'
      ? [k]
      : [],
  );
  if (
    !indices.includes(station) ||
    indices.length < 2 ||
    reference.run.state !== 'won'
  )
    throw Error(title + ' has no credible alternatives');
  let answer = null;
  for (const mode of options) {
    for (const change of adjustments(shape, mode)) {
      const bad = fieldMachine(m, fit, station, change),
        observed = tapeFor(M, bad),
        diff = firstDifference(observed, reference);
      if (
        !diff ||
        ![-3, -2, -1, 0, 1, 2, 3].every(
          (off) =>
            trial(M, bad, null, off).state === 'miss' &&
            trial(M, full, null, off).state === 'won',
        )
      )
        continue;
      answer = {
        id: title.toLowerCase().replaceAll(' ', '-'),
        title,
        source: m.id,
        fit,
        station,
        change,
        mode,
        indices,
      };
      break;
    }
    if (answer) break;
  }
  if (!answer) throw Error('No stable difference for ' + title);
  casesOut.push(answer);
  console.log(n, title, answer.mode, indices.length);
}
fs.writeFileSync(
  new URL('../one-part-missing/fault-desk/cases.js', import.meta.url),
  '// Generated by scripts/author-faults.mjs. Stations are indices in the assembled machine.\nexport const cases = [\n' +
    casesOut.map((c) => '  ' + JSON.stringify(c) + ',').join('\n') +
    '\n];\n',
);
